/* ===== Episode Link Helper ===== */
function getEpLink(epNum) {
  const key = String(epNum).replace(/^0+/, '') || epNum;
  return INSTA_LINKS[key] || INSTA_LINKS[epNum] || null;
}

/* ===== Mobile Hamburger ===== */
document.addEventListener('DOMContentLoaded', function() {
  const hamburger = document.querySelector('.hamburger');
  const navLinks = document.querySelector('.nav-links');
  if (hamburger && navLinks) {
    hamburger.addEventListener('click', function(e) {
      e.stopPropagation();
      navLinks.classList.toggle('open');
    });
    document.addEventListener('click', function(e) {
      if (!navLinks.contains(e.target) && !hamburger.contains(e.target)) {
        navLinks.classList.remove('open');
      }
    });
    navLinks.querySelectorAll('a').forEach(function(a) {
      a.addEventListener('click', function() { navLinks.classList.remove('open'); });
    });
  }

  /* ===== Scroll Fade-In ===== */
  const observer = new IntersectionObserver(function(entries) {
    entries.forEach(function(entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add('visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1 });
  document.querySelectorAll('.fade-in').forEach(function(el) { observer.observe(el); });

  /* ===== Auto-link Ep tags ===== */
  document.querySelectorAll('.ep-link').forEach(function(el) {
    const epNum = el.getAttribute('data-ep');
    if (epNum) {
      const link = getEpLink(epNum);
      if (link) {
        el.addEventListener('click', function() { window.open(link, '_blank'); });
        el.title = '📺 Instagram에서 원본 영상 보기';
      }
    }
  });

  /* ===== Active nav highlight ===== */
  const currentPage = window.location.pathname.split('/').pop() || 'index.html';
  document.querySelectorAll('.nav-links a').forEach(function(a) {
    const href = a.getAttribute('href');
    if (href === currentPage || (currentPage === '' && href === 'index.html')) {
      a.classList.add('active');
    }
  });
});
